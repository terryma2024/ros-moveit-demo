"""Phase 2 of the formal head search calibration: sealed geometry, generated candidates, coverage.

The phase reads the sealed camera geometry (`horizontal_fov_rad`, `lock_valid_neck_rad` and the
`required_search_domain_rad` the safe-interval calibration projects from the legal pick workspace),
generates the coarse-step candidates design section 7.1 allows - every one of them at most
`horizontal_fov_rad / 2`, never a fixed step taken on faith - and chooses the largest candidate whose
bounded two-way sweep covers the whole required domain from every anchor the seal declares. Coverage is
proved over the stable stops' field-of-view union, never over an accumulated angle, and a second,
deliberately different derivation (the repository's `independent_sweep_check`) has to agree before the
proof is issued. Each neck target of the chosen plan then carries its own sweep-check receipt.

Two refusals belong to this phase, spelled exactly as the plan fixes them: `CAL_DOMAIN_UNCOVERED` when
no generated candidate can cover the required domain, and `CAL_SWEEP_RECEIPT_MISSING` when a neck target
has no receipt of its own. A sealed geometry the seal cannot vouch for is refused with phase 1's own
`CAL_INPUT_UNSEALED`: phase 1 performs the validation and this phase re-raises its refusal unchanged in
code and detail, chained to the original.

Nothing here commands motion, starts ROS, MuJoCo or a detector, or touches a controller: the phase
produces a plan, a coverage proof and receipts. Nothing is written unless the caller passes an explicit
`output_path`, and the phase document is the only file this module ever creates.
"""

from __future__ import annotations

import hashlib
import json
import math
import re
from collections.abc import Mapping, Sequence
from pathlib import Path

from so101_demo.act.head_search_calibration_inputs import (
    CAL_INPUT_UNSEALED,
    CalibrationInputsRefused,
    validate_sealed_inputs,
)
from so101_demo.act.head_search_domain import (
    HeadSearchDomainError,
    bounded_search_stops,
    coverage_is_complete,
    independent_sweep_check,
)
from so101_demo.perception_benchmark.contracts import canonical_sha256

SCHEMA_VERSION = 1
KIND = "head_search_calibration_geometry"
PHASE = "geometry_coverage"

#: this phase's two refusals, plus the phase-1 code it re-raises for a geometry the seal cannot vouch for
CAL_DOMAIN_UNCOVERED = "CAL_DOMAIN_UNCOVERED"
CAL_SWEEP_RECEIPT_MISSING = "CAL_SWEEP_RECEIPT_MISSING"
REFUSAL_CODES = (CAL_INPUT_UNSEALED, CAL_DOMAIN_UNCOVERED, CAL_SWEEP_RECEIPT_MISSING)

#: the one sealed input this phase reads; the other five stay phase 1's
GEOMETRY_INPUT_NAME = "geometry_seal"

#: the candidates are generated by dividing the sealed half field of view by these divisors, largest
#: first, and are never enumerated from a candidate document: every one of them is at most half a field
#: of view by construction, which is exactly the bound design section 7.1 puts on the choice
CANDIDATE_DIVISORS = (1, 2, 4, 8, 16)

CANDIDATE_GENERATION_RULE = (
    "horizontal_fov_rad / 2 divided by each of the candidate divisors, plus the sealed "
    "coarse_step_candidate_rad when it does not exceed half the field of view"
)
SELECTION_RULE = (
    "the largest generated candidate whose bounded two-way sweep covers the whole "
    "required_search_domain_rad from every anchor the seal declares; the val zero-missed-sweep and "
    "lock-time evidence design section 7.1 also requires belongs to phase 6"
)

_SHA256 = re.compile(r"[0-9a-f]{64}")


class CalibrationGeometryRefused(CalibrationInputsRefused):
    """A phase-2 refusal, carrying the exact code the run records and stops on.

    It is a phase-1 refusal as well, so a caller that catches `CalibrationInputsRefused` catches every
    refusal of both phases and reads the code off the exception.
    """


def _finite(value) -> bool:
    return type(value) in (int, float) and math.isfinite(value)


def _interval(name: str, value) -> tuple[float, float]:
    """One ordered finite interval, or a plain `ValueError` for a caller that passed something else."""

    if isinstance(value, (str, bytes)) or not isinstance(value, Sequence) or len(value) != 2:
        raise ValueError(f"{name} must be two finite ordered bounds")
    low, high = (float(bound) for bound in value)
    if not math.isfinite(low) or not math.isfinite(high) or low >= high:
        raise ValueError(f"{name} must be two finite ordered bounds")
    return low, high


def _positive(name: str, value) -> float:
    result = float(value)
    if not math.isfinite(result) or result <= 0.0:
        raise ValueError(f"{name} must be finite and positive")
    return result


def _anchors(anchors_rad) -> dict[str, float]:
    """One `{name: angle}` mapping, or a plain `ValueError` for a caller that passed something else."""

    if not isinstance(anchors_rad, Mapping):
        raise ValueError("anchors_rad must map each anchor name to its neck angle")
    anchors: dict[str, float] = {}
    for name, angle in anchors_rad.items():
        if type(name) is not str or not name or not _finite(angle):
            raise ValueError("each anchor must be named and carry a finite neck angle")
        anchors[name] = float(angle)
    return anchors


def _unsealed(path, detail: str) -> CalibrationGeometryRefused:
    return CalibrationGeometryRefused(CAL_INPUT_UNSEALED, f"{path}: {detail}")


def _document_positive(document: Mapping, name: str, path) -> float:
    if name not in document:
        raise _unsealed(path, f"the sealed geometry declares no {name}")
    try:
        return _positive(name, document[name])
    except (TypeError, ValueError) as error:
        raise _unsealed(path, str(error)) from error


def _document_interval(document: Mapping, name: str, path) -> tuple[float, float]:
    if name not in document:
        raise _unsealed(path, f"the sealed geometry declares no {name}")
    try:
        return _interval(name, document[name])
    except (TypeError, ValueError) as error:
        raise _unsealed(path, str(error)) from error


def _document_anchors(document: Mapping, path) -> dict[str, float]:
    """The declared anchors and their neck start angles.

    The campaign seal lists anchor names and carries each anchor's start angle in `in_frame_matrix`
    under `neck_start_rad`; a mapping of `name -> {"neck_rad": angle}` is accepted too, exactly as the
    existing smoke entry point reads both shapes.
    """

    declared = document.get("anchors")
    if not declared:
        raise _unsealed(path, "the sealed geometry declares no anchors")
    matrix = document.get("in_frame_matrix") or {}
    if not isinstance(matrix, Mapping):
        raise _unsealed(path, "in_frame_matrix must be a mapping of anchors")
    anchors: dict[str, float] = {}
    if isinstance(declared, Mapping):
        entries = [(name, entry) for name, entry in declared.items()]
    elif isinstance(declared, (list, tuple)):
        entries = [(name, matrix.get(name)) for name in declared]
    else:
        raise _unsealed(path, "anchors must be a list of names or a mapping of names to angles")
    for name, entry in entries:
        if type(name) is not str or not name:
            raise _unsealed(path, "every anchor must be named")
        angle = None
        if isinstance(entry, Mapping):
            angle = entry.get("neck_start_rad", entry.get("neck_rad"))
        if angle is None and isinstance(matrix.get(name), Mapping):
            angle = matrix[name].get("neck_start_rad", matrix[name].get("neck_rad"))
        if not _finite(angle):
            raise _unsealed(path, f"the anchor {name!r} declares no finite neck start angle")
        anchors[name] = float(angle)
    if not anchors:
        raise _unsealed(path, "the sealed geometry declares no anchors")
    return anchors


def load_sealed_geometry(sealed_inputs) -> dict:
    """Validate the seal through phase 1 and read the geometry values out of the sealed document.

    Phase 1 digests all six controlled dependencies, so an absent geometry or one whose bytes no longer
    match the declared digest is refused there with `CAL_INPUT_UNSEALED`; this phase re-raises that
    refusal with the same code and detail. The document is then read again and re-digested, its own
    `seal_sha256` has to be the canonical digest of its body, and every field this phase consumes has to
    be present and well formed - anything else is refused with the same phase-1 code.
    """

    try:
        manifest = validate_sealed_inputs(sealed_inputs)
    except CalibrationInputsRefused as error:
        raise CalibrationGeometryRefused(error.code, error.detail) from error

    declaration = manifest["inputs"][GEOMETRY_INPUT_NAME]
    path = Path(declaration["path"])
    try:
        payload = path.read_bytes()
    except OSError as error:
        raise _unsealed(
            path,
            f"the sealed geometry is absent or unreadable ({error.strerror or error})",
        ) from error
    measured = hashlib.sha256(payload).hexdigest()
    if measured != declaration["sha256"]:
        raise _unsealed(
            path,
            f"the geometry digests to {measured} but the seal declares {declaration['sha256']!r}",
        )
    try:
        document = json.loads(payload.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        raise _unsealed(path, f"the sealed geometry is not a JSON document ({error})") from error
    if not isinstance(document, Mapping):
        raise _unsealed(path, "the sealed geometry must be a JSON object")

    seal_sha256 = document.get("seal_sha256")
    body = {key: value for key, value in document.items() if key != "seal_sha256"}
    try:
        recomputed = canonical_sha256(body)
    except ValueError as error:
        raise _unsealed(path, f"the sealed geometry is not a finite JSON document ({error})") from error
    if type(seal_sha256) is not str or seal_sha256 != recomputed:
        raise _unsealed(
            path,
            f"seal_sha256 {seal_sha256!r} is not the canonical digest {recomputed} of the geometry body",
        )

    horizontal_fov_rad = _document_positive(document, "horizontal_fov_rad", path)
    lock_valid_neck_rad = _document_interval(document, "lock_valid_neck_rad", path)
    required_search_domain_rad = _document_interval(document, "required_search_domain_rad", path)
    declared_candidate = document.get("coarse_step_candidate_rad")
    if declared_candidate is not None:
        try:
            declared_candidate = _positive("coarse_step_candidate_rad", declared_candidate)
        except (TypeError, ValueError) as error:
            raise _unsealed(path, str(error)) from error
    anchors = _document_anchors(document, path)

    return {
        "sealed_geometry": {
            "input": GEOMETRY_INPUT_NAME,
            "path": declaration["path"],
            "sha256": declaration["sha256"],
            "size_bytes": declaration["size_bytes"],
            "seal_sha256": seal_sha256,
            "manifest_sha256": manifest["manifest_sha256"],
        },
        "geometry": {
            "horizontal_fov_rad": horizontal_fov_rad,
            "lock_valid_neck_rad": [lock_valid_neck_rad[0], lock_valid_neck_rad[1]],
            "required_search_domain_rad": [
                required_search_domain_rad[0],
                required_search_domain_rad[1],
            ],
            "sealed_coarse_step_candidate_rad": declared_candidate,
            "anchors_rad": dict(anchors),
        },
    }


def generate_coarse_step_candidates(
    horizontal_fov_rad, *, sealed_candidate_rad=None
) -> tuple[float, ...]:
    """Generate the coarse-step candidates, largest first, every one at most half a field of view.

    The candidates are derived from the sealed field of view - half of it, then that half divided by
    each of `CANDIDATE_DIVISORS` - and the sealed `coarse_step_candidate_rad` joins them only when it
    does not exceed half the field of view, which is the bound design section 7.1 fixes. A step above
    that bound is never generated, whatever a document declares.
    """

    fov = _positive("horizontal_fov_rad", horizontal_fov_rad)
    half = fov / 2.0
    candidates = {half / divisor for divisor in CANDIDATE_DIVISORS}
    if sealed_candidate_rad is not None:
        sealed = _positive("sealed_candidate_rad", sealed_candidate_rad)
        if sealed <= half:
            candidates.add(sealed)
    return tuple(sorted((candidate for candidate in candidates if 0.0 < candidate <= half), reverse=True))


def _plans_for_candidate(
    *,
    coarse_step_rad: float,
    horizontal_fov_rad: float,
    required_search_domain_rad,
    safe_interval_rad,
    anchors_rad: Mapping[str, float],
) -> tuple[dict | None, str]:
    """The bounded two-way plan per anchor, or the reason this candidate cannot cover the domain.

    A plan only counts when every stop sits inside the safe interval (the planner guarantees that or
    refuses), when the stops' field-of-view union covers the required domain, and when the independent
    sweep check - a second derivation that walks the domain point by point and inspects the legs between
    stops - agrees.
    """

    if not anchors_rad:
        return None, "no anchor is declared, so no bounded sweep can cover the required domain"
    plans = {}
    for name, anchor in anchors_rad.items():
        try:
            plan = bounded_search_stops(
                anchor_rad=anchor,
                required_domain_rad=required_search_domain_rad,
                safe_interval_rad=safe_interval_rad,
                horizontal_fov_rad=horizontal_fov_rad,
                coarse_step_rad=coarse_step_rad,
            )
        except HeadSearchDomainError as error:
            return None, f"anchor {name}: {error}"
        if not coverage_is_complete(plan, required_domain_rad=required_search_domain_rad):
            return None, (
                f"anchor {name}: the field-of-view union of the stops does not cover the required domain"
            )
        checked, reason = independent_sweep_check(
            plan, required_domain_rad=required_search_domain_rad
        )
        if not checked:
            return None, f"anchor {name}: the independent sweep check disagrees ({reason})"
        plans[name] = plan
    return plans, "covered"


def choose_coarse_step_candidate(
    *,
    horizontal_fov_rad,
    required_search_domain_rad,
    safe_interval_rad,
    anchors_rad,
    sealed_candidate_rad=None,
) -> dict:
    """Generate the candidates, try each largest first, and choose the largest one that covers.

    Every candidate's verdict is recorded, so the choice cites the candidate document rather than an
    unexplained number. When no generated candidate covers the required domain the phase refuses with
    `CAL_DOMAIN_UNCOVERED`, naming each candidate and why it could not cover.
    """

    fov = _positive("horizontal_fov_rad", horizontal_fov_rad)
    required = _interval("required_search_domain_rad", required_search_domain_rad)
    safe = _interval("safe_interval_rad", safe_interval_rad)
    anchors = _anchors(anchors_rad)
    sealed = None if sealed_candidate_rad is None else _positive(
        "sealed_candidate_rad", sealed_candidate_rad
    )
    half = fov / 2.0

    candidates = generate_coarse_step_candidates(fov, sealed_candidate_rad=sealed)
    records = []
    chosen: float | None = None
    chosen_index: int | None = None
    for index, candidate in enumerate(candidates):
        plans, reason = _plans_for_candidate(
            coarse_step_rad=candidate,
            horizontal_fov_rad=fov,
            required_search_domain_rad=required,
            safe_interval_rad=safe,
            anchors_rad=anchors,
        )
        records.append(
            {
                "coarse_step_rad": candidate,
                "source": "sealed" if sealed is not None and sealed == candidate else "generated",
                "fraction_of_half_fov": candidate / half,
                "covers_required_domain": plans is not None,
                "reason": reason,
                "stop_count": 0
                if plans is None
                else sum(len(plan.targets_rad) for plan in plans.values()),
            }
        )
        if plans is not None and chosen is None:
            chosen, chosen_index = candidate, index
    if chosen is None:
        detail = "; ".join(
            f"{record['coarse_step_rad']} ({record['fraction_of_half_fov']} of half the field of view): "
            f"{record['reason']}"
            for record in records
        )
        raise CalibrationGeometryRefused(
            CAL_DOMAIN_UNCOVERED,
            f"no generated coarse-step candidate covers the required domain {list(required)}: {detail}",
        )
    return {
        "candidates": records,
        "chosen_candidate_rad": chosen,
        "chosen_index": chosen_index,
        "selection_rule": SELECTION_RULE,
    }


def prove_required_domain_coverage(
    *,
    horizontal_fov_rad,
    required_search_domain_rad,
    safe_interval_rad,
    coarse_step_candidate_rad,
    anchors_rad,
) -> dict:
    """Prove the chosen candidate's bounded two-way sweep covers the required domain, per anchor.

    The proof names each anchor's stops, so a later phase can see what was commanded without this phase
    commanding anything, and it records both derivations: the field-of-view union over the stable stops
    and the independent sweep check. A candidate that cannot cover refuses as `CAL_DOMAIN_UNCOVERED`.
    """

    fov = _positive("horizontal_fov_rad", horizontal_fov_rad)
    step = _positive("coarse_step_candidate_rad", coarse_step_candidate_rad)
    required = _interval("required_search_domain_rad", required_search_domain_rad)
    safe = _interval("safe_interval_rad", safe_interval_rad)
    anchors = _anchors(anchors_rad)
    if step > fov / 2.0:
        raise CalibrationGeometryRefused(
            CAL_DOMAIN_UNCOVERED,
            f"the candidate step {step} exceeds half the field of view {fov / 2.0}, so no bounded "
            f"sweep can cover the required domain {list(required)}",
        )
    plans, reason = _plans_for_candidate(
        coarse_step_rad=step,
        horizontal_fov_rad=fov,
        required_search_domain_rad=required,
        safe_interval_rad=safe,
        anchors_rad=anchors,
    )
    if plans is None:
        raise CalibrationGeometryRefused(
            CAL_DOMAIN_UNCOVERED,
            f"the candidate step {step} does not cover the required domain {list(required)}: {reason}",
        )
    anchor_proofs = []
    for name, plan in plans.items():
        checked, check_reason = independent_sweep_check(
            plan, required_domain_rad=required
        )
        anchor_proofs.append(
            {
                "anchor": name,
                "anchor_rad": plan.anchor_rad,
                "targets_rad": [float(target) for target in plan.targets_rad],
                "stop_count": len(plan.targets_rad),
                "coverage_complete": True,
                "independent_sweep_check": {"checked": bool(checked), "reason": check_reason},
            }
        )
    return {
        "required_search_domain_rad": [required[0], required[1]],
        "safe_interval_rad": [safe[0], safe[1]],
        "horizontal_fov_rad": fov,
        "coarse_step_candidate_rad": step,
        "sweep": "bounded_two_way",
        "coverage": "horizontal_fov_union_of_stops",
        "anchors": anchor_proofs,
        "coverage_complete": True,
    }


def _binding(generation, measurement_plan_sha256) -> None:
    """A malformed binding is a caller bug, so it raises a plain `ValueError` without a refusal code."""

    if generation is not None and (type(generation) is not str or not generation):
        raise ValueError("generation must be a non-empty name when it is given")
    if measurement_plan_sha256 is not None and (
        type(measurement_plan_sha256) is not str
        or _SHA256.fullmatch(measurement_plan_sha256) is None
    ):
        raise ValueError("measurement_plan_sha256 must be a sha256 digest when it is given")


def sweep_check_receipts(
    *, coverage_proof, generation=None, measurement_plan_sha256=None
) -> tuple[dict, ...]:
    """Issue one independent sweep-check receipt per neck target of the proof.

    Every receipt binds the same generation, the same measurement plan and the same safe interval - the
    contract design section 8.2 fixes for all neck targets - and its own digest, so a receipt cannot be
    copied from one target to another. The receipt is a computed check, never a motion: the phase issues
    receipts and commands nothing.
    """

    _binding(generation, measurement_plan_sha256)
    required = list(coverage_proof["required_search_domain_rad"])
    safe = list(coverage_proof["safe_interval_rad"])
    fov = coverage_proof["horizontal_fov_rad"]
    step = coverage_proof["coarse_step_candidate_rad"]
    receipts = []
    for anchor in coverage_proof["anchors"]:
        targets = list(anchor["targets_rad"])
        verdict = anchor["independent_sweep_check"]
        for index, target in enumerate(targets):
            body = {
                "anchor": anchor["anchor"],
                "anchor_rad": float(anchor["anchor_rad"]),
                "target_rad": float(target),
                "target_index": index,
                "stop_count": len(targets),
                "coarse_step_candidate_rad": float(step),
                "horizontal_fov_rad": float(fov),
                "safe_interval_rad": safe,
                "required_search_domain_rad": required,
                "generation": generation,
                "measurement_plan_sha256": measurement_plan_sha256,
                "checker": "independent_sweep_check",
                "checked": bool(verdict["checked"]),
                "reason": str(verdict["reason"]),
                "motion_commanded": False,
            }
            receipts.append({**body, "receipt_sha256": canonical_sha256(body)})
    return tuple(receipts)


def require_sweep_check_receipts(*, coverage_proof, receipts) -> None:
    """Require exactly one clean, identified receipt per neck target, or refuse.

    A target whose receipt is missing, whose receipt does not carry a clean independent check, or whose
    receipt carries no digest of its own is refused as `CAL_SWEEP_RECEIPT_MISSING`; so is a receipt that
    belongs to no neck target of this sweep.
    """

    wanted = [
        (anchor["anchor"], float(target))
        for anchor in coverage_proof["anchors"]
        for target in anchor["targets_rad"]
    ]
    neck_targets = set(wanted)
    seen: dict[tuple[str, float], list] = {}
    for receipt in receipts:
        if not isinstance(receipt, Mapping) or "anchor" not in receipt or "target_rad" not in receipt:
            raise ValueError("a sweep-check receipt must name its anchor and its neck target")
        seen.setdefault((receipt["anchor"], float(receipt["target_rad"])), []).append(receipt)
    for name, target in wanted:
        group = seen.get((name, target), [])
        vouching = [
            receipt
            for receipt in group
            if receipt.get("checked") is True
            and _SHA256.fullmatch(str(receipt.get("receipt_sha256", ""))) is not None
        ]
        if vouching:
            continue
        if group:
            raise CalibrationGeometryRefused(
                CAL_SWEEP_RECEIPT_MISSING,
                f"the receipt for the neck target {target!r} of anchor {name!r} does not vouch for it: "
                f"checked={group[0].get('checked')!r}, "
                f"receipt_sha256={group[0].get('receipt_sha256')!r}",
            )
        raise CalibrationGeometryRefused(
            CAL_SWEEP_RECEIPT_MISSING,
            f"the neck target {target!r} of anchor {name!r} carries no independent sweep-check receipt",
        )
    for (name, target) in seen:
        if (name, target) not in neck_targets:
            raise CalibrationGeometryRefused(
                CAL_SWEEP_RECEIPT_MISSING,
                f"the receipt for the neck target {target!r} of anchor {name!r} belongs to no neck "
                f"target of this sweep",
            )


def validate_head_search_calibration_geometry(
    *,
    sealed_inputs,
    generation=None,
    measurement_plan_sha256=None,
    output_path=None,
) -> dict:
    """Produce phase 2's artefacts: the geometry values, the candidates, the proof and the receipts.

    The order is the plan's: read the sealed geometry, generate and choose the candidate, prove the
    bounded two-way sweep covers the required domain from every anchor, issue one receipt per neck
    target, and check that every target has its own. The CLI holds the generation and the measurement
    plan and passes them here, so every receipt binds the same pair. When `output_path` is given the
    phase document is written there and nowhere else; without it the phase writes nothing at all.
    """

    loaded = load_sealed_geometry(sealed_inputs)
    geometry = loaded["geometry"]
    choice = choose_coarse_step_candidate(
        horizontal_fov_rad=geometry["horizontal_fov_rad"],
        required_search_domain_rad=geometry["required_search_domain_rad"],
        safe_interval_rad=geometry["lock_valid_neck_rad"],
        anchors_rad=geometry["anchors_rad"],
        sealed_candidate_rad=geometry["sealed_coarse_step_candidate_rad"],
    )
    proof = prove_required_domain_coverage(
        horizontal_fov_rad=geometry["horizontal_fov_rad"],
        required_search_domain_rad=geometry["required_search_domain_rad"],
        safe_interval_rad=geometry["lock_valid_neck_rad"],
        coarse_step_candidate_rad=choice["chosen_candidate_rad"],
        anchors_rad=geometry["anchors_rad"],
    )
    receipts = sweep_check_receipts(
        coverage_proof=proof,
        generation=generation,
        measurement_plan_sha256=measurement_plan_sha256,
    )
    require_sweep_check_receipts(coverage_proof=proof, receipts=receipts)
    half = geometry["horizontal_fov_rad"] / 2.0
    declared = geometry["sealed_coarse_step_candidate_rad"]
    document = {
        "schema_version": SCHEMA_VERSION,
        "kind": KIND,
        "phase": PHASE,
        "sealed_geometry": loaded["sealed_geometry"],
        "geometry": geometry,
        "candidate_generation": {
            "rule": CANDIDATE_GENERATION_RULE,
            "divisors": list(CANDIDATE_DIVISORS),
            "half_fov_rad": half,
            "max_candidate_rad": half,
            "sealed_candidate_rad": declared,
            "sealed_candidate_within_half_fov": None if declared is None else declared <= half,
        },
        "candidates": choice["candidates"],
        "chosen_candidate_rad": choice["chosen_candidate_rad"],
        "chosen_candidate_index": choice["chosen_index"],
        "selection_rule": choice["selection_rule"],
        "coverage_proof": proof,
        "sweep_check_receipts": list(receipts),
        "sweep_check_receipts_complete": True,
        "motion_commanded": False,
    }
    if output_path is not None:
        target = Path(output_path)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(document, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return document
